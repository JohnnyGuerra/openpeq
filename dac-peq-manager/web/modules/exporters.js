/**
 * Host DSP Configuration Exporters (PipeWire filter-chain, EqualizerAPO, Wavelet GraphicEQ).
 * Mathematically synchronized with Python `src/dac_peq/exporters.py`.
 */

import { computeCompositeCurve, generateLogFrequencies } from "./biquad_math.js";

export function formatPipeWireConf(preset, bands, isFull = false, sinkTarget = "alsa_output.usb-Conexant_CX31993*") {
  const slug = (preset.slug || preset.name || "custom").toLowerCase().replace(/[^a-z0-9]+/g, "_");
  const numBands = bands.length;
  const preampDb = Number(preset.preamp ?? 0.0);
  const linear = Math.pow(10.0, preampDb / 20.0).toFixed(4);
  const typeMap = {
    PK: "bq_peaking",
    PEAK: "bq_peaking",
    PEAKING: "bq_peaking",
    LSQ: "bq_lowshelf",
    LOW_SHELF: "bq_lowshelf",
    LOWSHELF: "bq_lowshelf",
    HSQ: "bq_highshelf",
    HIGH_SHELF: "bq_highshelf",
    HIGHSHELF: "bq_highshelf",
  };

  let nodes = `                    # Preamp Gain Stage (${preampDb > 0 ? "+" : ""}${preampDb.toFixed(1)} dB)
                    { type = builtin, name = "preamp_fl", label = linear, control = { "Gain" = ${linear} } }
                    { type = builtin, name = "preamp_fr", label = linear, control = { "Gain" = ${linear} } }\n`;

  bands.forEach((b, i) => {
    const idx = i + 1;
    const label = typeMap[String(b.type || "PK").toUpperCase()] || "bq_peaking";
    const freq = Number(b.freq ?? 1000.0);
    const gain = Number(b.gain ?? 0.0);
    const q = Number(b.q ?? 1.0);
    nodes += `                    # Band ${idx}: ${b.type} ${freq}Hz ${gain}dB Q=${q}
                    { type = builtin, name = "eq_band${idx}_fl", label = ${label}, control = { "Freq" = ${freq.toFixed(1)}, "Gain" = ${gain.toFixed(2)}, "Q" = ${q.toFixed(2)} } }
                    { type = builtin, name = "eq_band${idx}_fr", label = ${label}, control = { "Freq" = ${freq.toFixed(1)}, "Gain" = ${gain.toFixed(2)}, "Q" = ${q.toFixed(2)} } }\n`;
  });

  let links = `                    { output = "preamp_fl:Out", input = "eq_band1_fl:In" }
                    { output = "preamp_fr:Out", input = "eq_band1_fr:In" }\n`;

  for (let i = 1; i < numBands; i++) {
    links += `                    { output = "eq_band${i}_fl:Out", input = "eq_band${i + 1}_fl:In" }
                    { output = "eq_band${i}_fr:Out", input = "eq_band${i + 1}_fr:In" }\n`;
  }

  return `# PipeWire filter-chain configuration for JCALLY JM6 Pro (Conexant CX31993)
# Preset: ${preset.name} (${numBands} Bands - ${isFull ? "Target Fidelity" : "Hardware Matches"})
# Generated by dac-peq-manager

context.modules = [
    {
        name = libpipewire-module-filter-chain
        args = {
            node.description = "JCALLY JM6 Pro DSP [${preset.name}]"
            media.name       = "JCALLY JM6 Pro DSP [${preset.name}]"
            filter.graph = {
                nodes = [
${nodes}                ]
                links = [
${links}                ]
                inputs  = [ "preamp_fl:In", "preamp_fr:In" ]
                outputs = [ "eq_band${numBands}_fl:Out", "eq_band${numBands}_fr:Out" ]
            }
            capture.props = {
                node.name        = "effect_input.jm6pro_${slug}"
                media.class      = "Audio/Sink"
                audio.position   = [ "FL", "FR" ]
            }
            playback.props = {
                node.name        = "effect_output.jm6pro_${slug}"
                node.target      = "${sinkTarget}"
                audio.position   = [ "FL", "FR" ]
                node.passive     = true
            }
        }
    }
]
`;
}

export function formatEqualizerApo(preset, bands, isFull = false) {
  const preampDb = Number(preset.preamp ?? 0.0);
  let txt = `# EqualizerAPO Configuration\n# Preset: ${preset.name} (${bands.length} Bands - ${isFull ? "Target Fidelity" : "Hardware Matches"})\n\nPreamp: ${preampDb > 0 ? "+" : ""}${preampDb.toFixed(1)} dB\n`;
  bands.forEach((b, i) => {
    const freq = Number(b.freq ?? 1000.0);
    const gain = Number(b.gain ?? 0.0);
    const q = Number(b.q ?? 1.0);
    txt += `Filter ${i + 1}: ON ${b.type} Fc ${freq.toFixed(1)} Hz Gain ${gain >= 0 ? "+" : ""}${gain.toFixed(1)} dB Q ${q.toFixed(2)}\n`;
  });
  return txt;
}

export function formatWaveletGraphicEq(bands, preampDb, points = 127) {
  const frequencies = generateLogFrequencies(points, 20.0, 20000.0);
  const curve = computeCompositeCurve(bands, preampDb, frequencies);
  const pairs = frequencies.map((f, i) => `${Math.round(f)} ${curve[i].toFixed(1)}`);
  return "GraphicEQ: " + pairs.join("; ") + "\n";
}

export function formatQudelixJson(preset, bands, isFull = false) {
  const preampDb = Number(preset.preamp ?? 0.0);
  const typeToQ5k = {
    PK: "PEAK",
    PEAK: "PEAK",
    PEAKING: "PEAK",
    LSQ: "LOW_SHELF",
    LOW_SHELF: "LOW_SHELF",
    LOWSHELF: "LOW_SHELF",
    HSQ: "HIGH_SHELF",
    HIGH_SHELF: "HIGH_SHELF",
    HIGHSHELF: "HIGH_SHELF",
  };

  const q5kBands = [];
  const totalSlots = 10;
  for (let i = 0; i < totalSlots; i++) {
    if (i < bands.length) {
      const b = bands[i];
      const ftype = typeToQ5k[String(b.type || "PK").toUpperCase()] || "PEAK";
      q5kBands.push({
        band: i,
        enable: b.enabled !== false ? 1 : 0,
        type: ftype,
        freq: Math.round(Number(b.freq || 1000.0)),
        gain: Number(Number(b.gain || 0.0).toFixed(1)),
        q: Number(Number(b.q || 1.0).toFixed(2)),
      });
    } else {
      q5kBands.push({
        band: i,
        enable: 0,
        type: "PEAK",
        freq: 1000,
        gain: 0.0,
        q: 1.0,
      });
    }
  }

  return JSON.stringify(
    {
      profile_name: preset.name || "custom",
      name: preset.name || "custom",
      description: preset.description || "Exported from dac-peq-manager",
      target: "Qudelix-5K Bluetooth & USB DAC/Amp",
      preamp_db: Number(preampDb.toFixed(1)),
      preamp: Number(preampDb.toFixed(1)),
      eq_mode: "USER",
      eq_list: q5kBands,
      bands: q5kBands,
    },
    null,
    2
  );
}

export function formatQudelixText(preset, bands, isFull = false) {
  const preampDb = Number(preset.preamp ?? 0.0);
  let txt = `# Qudelix-5K PEQ Profile: ${preset.name || "custom"}\n# Compatible with Qudelix-5K Chrome App & Mobile App import\nPreamp: ${preampDb > 0 ? "+" : ""}${preampDb.toFixed(1)} dB\n`;
  for (let i = 0; i < 10; i++) {
    const idx = i + 1;
    if (i < bands.length) {
      const b = bands[i];
      const freq = Number(b.freq || 1000.0);
      const gain = Number(b.gain || 0.0);
      const q = Number(b.q || 1.0);
      const state = b.enabled !== false ? "ON" : "OFF";
      txt += `Filter ${idx}: ${state} ${b.type || "PK"} Fc ${freq.toFixed(1)} Hz Gain ${gain >= 0 ? "+" : ""}${gain.toFixed(1)} dB Q ${q.toFixed(2)}\n`;
    } else {
      txt += `Filter ${idx}: OFF PK Fc 1000.0 Hz Gain +0.0 dB Q 1.00\n`;
    }
  }
  return txt;
}

/**
 * Universal Parametric EQ text / GraphWorks / Equalizer APO / CSV parser for Web client.
 */
export function parseParametricEq(rawText, defaultName = "imported_peq") {
  const text = (rawText || "").trim();
  if (!text) {
    throw new Error("Cannot parse empty configuration.");
  }

  // Handle JSON profile (e.g. Qudelix JSON)
  if (text.startsWith("{") && text.endsWith("}")) {
    try {
      const data = JSON.parse(text);
      const name = data.profile_name || data.name || defaultName;
      const preamp = Number(data.preamp_db ?? data.preamp ?? 0.0);
      const rawBands = data.eq_list || data.bands || [];
      const typeMap = {
        PEAK: "PK", PEAKING: "PK", PK: "PK",
        LOW_SHELF: "LSQ", LOWSHELF: "LSQ", LSQ: "LSQ", LS: "LSQ",
        HIGH_SHELF: "HSQ", HIGHSHELF: "HSQ", HSQ: "HSQ", HS: "HSQ",
      };
      const bands = [];
      rawBands.forEach((b, i) => {
        const enabled = b.enable !== 0 && b.enabled !== false;
        const gain = Number(b.gain || 0.0);
        if (!enabled && gain === 0.0) return;
        const ftype = typeMap[String(b.type || "PEAK").toUpperCase()] || "PK";
        bands.push({
          index: i + 1,
          type: ftype,
          freq: Number(b.freq || 1000.0),
          gain: gain,
          q: Number(b.q || 1.0),
          enabled: enabled,
        });
      });
      return {
        name,
        description: data.description || "Imported JSON profile",
        preamp,
        bands,
      };
    } catch (e) {
      // Fall through to text parsing if JSON parse failed
    }
  }

  const typeMap = {
    PK: "PK", PEAK: "PK", PEAKING: "PK",
    LS: "LSQ", LSQ: "LSQ", LOW_SHELF: "LSQ", LOWSHELF: "LSQ",
    HS: "HSQ", HSQ: "HSQ", HIGH_SHELF: "HSQ", HIGHSHELF: "HSQ",
  };

  const lines = text.split(/\r?\n/);
  let name = defaultName;
  let description = "Imported parametric EQ configuration";
  let preamp = 0.0;
  const bands = [];

  for (let rawLine of lines) {
    rawLine = rawLine.trim();
    if (!rawLine) continue;

    if (rawLine.startsWith("#") || rawLine.startsWith("//") || rawLine.startsWith(";")) {
      const commentBody = rawLine.replace(/^[#\/;]+\s*/, "");
      const lower = commentBody.toLowerCase();
      if (lower.startsWith("preset:") || lower.startsWith("name:") || lower.startsWith("profile:")) {
        name = commentBody.split(":")[1].trim();
      } else if (lower.startsWith("description:")) {
        description = commentBody.split(":")[1].trim();
      }
      continue;
    }

    const lowerLine = rawLine.toLowerCase();
    if (lowerLine.startsWith("preamp:") || lowerLine.startsWith("pre-amp:") || lowerLine.startsWith("preamp ") || lowerLine.startsWith("pre-amp ")) {
      const parts = rawLine.includes(":") ? rawLine.split(":")[1] : rawLine.split(/\s+/).slice(1).join(" ");
      const val = parseFloat(parts.replace(/dB/gi, "").replace(/\+/g, "").trim());
      if (!isNaN(val)) preamp = val;
      continue;
    }

    if (lowerLine.startsWith("filter")) {
      let content = rawLine;
      if (content.includes(":")) {
        content = content.split(":")[1].trim();
      } else {
        const tokens = content.split(/\s+/);
        if (tokens.length > 1 && tokens[0].toLowerCase() === "filter") {
          content = tokens.slice(1).join(" ");
        }
      }

      let tokens = content.split(/\s+/);
      if (!tokens.length) continue;

      let state = "ON";
      if (["ON", "OFF"].includes(tokens[0].toUpperCase())) {
        state = tokens[0].toUpperCase();
        tokens = tokens.slice(1);
      }
      if (!tokens.length) continue;

      const rawType = tokens[0].toUpperCase();
      const ftype = typeMap[rawType] || "PK";

      let freq = null, gain = null, q = null;
      for (let i = 0; i < tokens.length; i++) {
        const tLower = tokens[i].toLowerCase();
        if (tLower === "fc" && i + 1 < tokens.length) {
          freq = parseFloat(tokens[i + 1].toLowerCase().replace("hz", ""));
        } else if (tLower === "gain" && i + 1 < tokens.length) {
          gain = parseFloat(tokens[i + 1].toLowerCase().replace(/db|\+/gi, ""));
        } else if (tLower === "q" && i + 1 < tokens.length) {
          q = parseFloat(tokens[i + 1]);
        }
      }

      if (freq !== null && !isNaN(freq) && gain !== null && !isNaN(gain)) {
        if (state === "OFF" && gain === 0.0) continue;
        bands.push({
          index: bands.length + 1,
          type: ftype,
          freq: Number(freq),
          gain: Number(gain),
          q: q !== null && !isNaN(q) ? Number(q) : 1.0,
          enabled: state === "ON",
        });
      }
      continue;
    }

    // CSV / TSV fallback
    const delimiter = rawLine.includes(",") ? "," : (rawLine.includes("\t") ? "\t" : null);
    if (delimiter) {
      const parts = rawLine.split(delimiter).map(p => p.trim());
      if (["type", "filter", "freq", "index"].some(h => parts[0].toLowerCase().includes(h))) continue;
      try {
        let cType, cFreq, cGain, cQ;
        if (/^\d+$/.test(parts[0]) && parts.length >= 5) {
          cType = parts[1].toUpperCase();
          cFreq = parseFloat(parts[2].toLowerCase().replace("hz", ""));
          cGain = parseFloat(parts[3].toLowerCase().replace(/db|\+/gi, ""));
          cQ = parseFloat(parts[4]);
        } else if (parts.length >= 4) {
          cType = parts[0].toUpperCase();
          cFreq = parseFloat(parts[1].toLowerCase().replace("hz", ""));
          cGain = parseFloat(parts[2].toLowerCase().replace(/db|\+/gi, ""));
          cQ = parseFloat(parts[3]);
        }
        if (!isNaN(cFreq) && !isNaN(cGain) && !isNaN(cQ)) {
          bands.push({
            index: bands.length + 1,
            type: typeMap[cType] || "PK",
            freq: Number(cFreq),
            gain: Number(cGain),
            q: Number(cQ),
            enabled: true,
          });
        }
      } catch (err) {
        // ignore malformed line
      }
    }
  }

  if (!bands.length) {
    throw new Error("No valid parametric EQ filters found in input.");
  }

  return {
    name,
    description,
    preamp,
    bands,
  };
}
