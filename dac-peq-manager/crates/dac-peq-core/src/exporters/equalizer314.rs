use crate::models::{FilterType, PeqPreset};

/// Formats a PeqPreset into an Equalizer314-compatible EqualizerAPO configuration.
pub fn format_equalizer314_export(preset: &PeqPreset) -> String {
    let mut lines = Vec::new();
    lines.push("# Equalizer314 Configuration generated by OpenPEQ (dac-peq-manager)".to_string());
    lines.push(format!("# Preset: {}", preset.name));
    if let Some(desc) = &preset.description {
        lines.push(format!("# Description: {desc}"));
    }
    lines.push(format!("Preamp: {:+.2} dB", preset.preamp));

    for (i, b) in preset.bands.iter().enumerate() {
        let apo_type = match b.filter_type {
            FilterType::Peaking => "PK",
            FilterType::LowShelf => "LSC",
            FilterType::HighShelf => "HSC",
            FilterType::Bypass => "PK",
        };
        let state = if b.enabled { "ON" } else { "OFF" };
        let gain = if b.enabled { b.gain } else { 0.0 };
        lines.push(format!(
            "Filter {}: {} {} Fc {:.1} Hz Gain {:+.2} dB Q {:.2}",
            i + 1,
            state,
            apo_type,
            b.freq,
            gain,
            b.q
        ));
    }

    lines.join("\n") + "\n"
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::models::BiquadBand;

    #[test]
    fn test_format_equalizer314() {
        let preset = PeqPreset {
            name: "IEM Test".to_string(),
            description: Some("Test Preset".to_string()),
            preamp: -2.5,
            slot_id: None,
            bands: vec![
                BiquadBand::new(FilterType::LowShelf, 105.0, 3.5, 0.71),
                BiquadBand::new(FilterType::Peaking, 2500.0, -1.2, 1.41),
            ],
            full_bands: None,
        };

        let txt = format_equalizer314_export(&preset);
        assert!(txt.contains("# Preset: IEM Test"));
        assert!(txt.contains("Preamp: -2.50 dB"));
        assert!(txt.contains("Filter 1: ON LSC Fc 105.0 Hz Gain +3.50 dB Q 0.71"));
        assert!(txt.contains("Filter 2: ON PK Fc 2500.0 Hz Gain -1.20 dB Q 1.41"));
    }
}
